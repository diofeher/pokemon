#!/usr/bin/env node
/**
 * Fetch Pokemon 1-1025 from PokeAPI and generate src/data/pokemon.ts
 *
 * Usage: node scripts/fetch-pokemon-data.mjs
 *
 * Uses a local .cache/ directory to avoid re-fetching on subsequent runs.
 * Rate-limited to be polite to the PokeAPI server.
 */
import { writeFileSync, mkdirSync, existsSync, readFileSync } from "fs";
import { join, dirname } from "path";
import { fileURLToPath } from "url";
import { computeDifficulty } from "./lib/difficulty-heuristics.mjs";
import { resolveRegion } from "./lib/region-mapping.mjs";

const __dirname = dirname(fileURLToPath(import.meta.url));
const CACHE_DIR = join(__dirname, ".cache");
const OUT_FILE = join(__dirname, "..", "src", "data", "pokemon.ts");
const TOTAL = 1025;
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function cachedFetchJson(url, cacheKey) {
  const cachePath = join(CACHE_DIR, `${cacheKey}.json`);
  if (existsSync(cachePath)) {
    return JSON.parse(readFileSync(cachePath, "utf8"));
  }
  const res = await fetch(url);
  if (!res.ok) throw new Error(`HTTP ${res.status} for ${url}`);
  const data = await res.json();
  mkdirSync(CACHE_DIR, { recursive: true });
  writeFileSync(cachePath, JSON.stringify(data));
  return data;
}

function capitalize(s) {
  return s
    .split("-")
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
    .join("-");
}

function extractGenNumber(genUrl) {
  const match = genUrl.match(/\/(\d+)\/$/);
  return match ? Number(match[1]) : 1;
}

function renderTsModule(pokemonList) {
  const header = `// AUTO-GENERATED by scripts/fetch-pokemon-data.mjs — DO NOT EDIT BY HAND
// Re-run: npm run fetch-data
import type { Pokemon } from "../types/pokemon";

export const POKEMON: Pokemon[] = [\n`;

  const entries = pokemonList.map((p) => {
    const types = JSON.stringify(p.types);
    return `  { id: ${p.id}, name: ${JSON.stringify(p.name)}, types: ${types} as Pokemon["types"], generation: ${p.generation}, regionId: "${p.regionId}", spriteUrl: "${p.spriteUrl}", isLegendary: ${p.isLegendary}, isMythical: ${p.isMythical}, isStarter: ${p.isStarter}, popularity: "${p.popularity}" },`;
  });

  return header + entries.join("\n") + "\n];\n";
}

async function main() {
  const results = [];
  let failed = 0;

  console.log(`Fetching ${TOTAL} Pokemon from PokeAPI...\n`);

  for (let id = 1; id <= TOTAL; id++) {
    try {
      const p = await cachedFetchJson(
        `https://pokeapi.co/api/v2/pokemon/${id}`,
        `pokemon-${id}`
      );
      const species = await cachedFetchJson(
        `https://pokeapi.co/api/v2/pokemon-species/${id}`,
        `species-${id}`
      );

      const generation = extractGenNumber(species.generation.url);
      const types = p.types
        .sort((a, b) => a.slot - b.slot)
        .map((t) => t.type.name);

      const entry = {
        id,
        name: capitalize(species.name),
        types,
        generation,
        regionId: resolveRegion(generation),
        spriteUrl: `https://raw.githubusercontent.com/PokeAPI/sprites/master/sprites/pokemon/other/official-artwork/${id}.png`,
        isLegendary: species.is_legendary,
        isMythical: species.is_mythical,
        isStarter: false, // set below
      };

      entry.popularity = computeDifficulty(entry);
      // isStarter is already handled in the difficulty heuristic via STARTER_IDS,
      // but we also want it on the data model
      entry.isStarter = [
        1,2,3,4,5,6,7,8,9,
        152,153,154,155,156,157,158,159,160,
        252,253,254,255,256,257,258,259,260,
        387,388,389,390,391,392,393,394,395,
        390,391,392,393,394,395,
        495,496,497,498,499,500,501,502,503,
        650,651,652,653,654,655,656,657,658,
        722,723,724,725,726,727,728,729,730,
        810,811,812,813,814,815,816,817,818,
        906,907,908,909,910,911,912,913,914,
      ].includes(id);

      results.push(entry);

      if (id % 100 === 0 || id === TOTAL) {
        console.log(`  ✅ ${id}/${TOTAL} (${entry.name})`);
      }
    } catch (err) {
      console.log(`  ❌ #${id}: ${err.message}`);
      failed++;
    }

    // Rate limit: 30ms between requests (only matters on first run, cache makes reruns instant)
    if (!existsSync(join(CACHE_DIR, `pokemon-${id}.json`))) {
      await sleep(30);
    }
  }

  writeFileSync(OUT_FILE, renderTsModule(results));
  console.log(
    `\n✅ Done. ${results.length} Pokemon generated, ${failed} failed.`
  );
  console.log(`   Output: ${OUT_FILE}`);
}

main().catch(console.error);
